def subjects() -> list[str]:
    return list(CURRICULUM.keys())


def major_chapters(subjects_sel: list[str]) -> list[str]:
    """선택된 과목들의 대단원 목록 (중복 제거, 순서 보존)."""
    seen = set()
    out = []
    for s in subjects_sel:
        for major in CURRICULUM.get(s, {}).keys():
            if major not in seen:
                seen.add(major)
                out.append(major)
    return out


def minor_chapters(subjects_sel: list[str],
                   majors_sel: list[str]) -> list[str]:
    """선택된 (과목, 대단원) 조합의 중단원 목록."""
    seen = set()
    out = []
    for s in subjects_sel:
        subj_map = CURRICULUM.get(s, {})
        for major in majors_sel:
            for minor in subj_map.get(major, []):
                if minor not in seen:
                    seen.add(minor)
                    out.append(minor)
    return out


def all_minor_chapters_in_subjects(subjects_sel: list[str]) -> list[str]:
    """선택된 과목들의 모든 중단원."""
    return minor_chapters(subjects_sel, major_chapters(subjects_sel))


def expand_to_minors(subjects_sel: list[str],
                     majors_sel: list[str],
                     minors_sel: list[str]) -> list[str]:
    """필터 입력을 최종 중단원 리스트로 확장.

    - 중단원 직접 선택돼있으면 그것 사용
    - 아니면 대단원 안의 모든 중단원
    - 아니면 과목 안의 모든 중단원
    - 아무것도 안 선택되면 빈 리스트 (= '전체' 의미, 호출측에서 처리)
    """
    if minors_sel:
        return minors_sel
    if majors_sel:
        return minor_chapters(subjects_sel or subjects(), majors_sel)
    if subjects_sel:
        return all_minor_chapters_in_subjects(subjects_sel)
    return []
